namespace report_coursemanager\local\wiris;

/**
 * Finds Wiris/MathType formulas in a piece of HTML and replaces them with LaTeX for MathJax.
 *
 * Three storage forms are handled:
 *  - SafeXML, the default Wiris storage: «math xmlns=¨...¨»«mn»1«/mn»«/math»
 *  - Wiris images: <img class="Wirisformula" data-mathml="«math ...»" ...>
 *  - plain MathML: <math xmlns="...">...</math> (Wiris "xml" save mode, or pasted MathML)
 *
 * Pure PHP, no dependency on Moodle.
 *
 * @package    report_coursemanager
 * @copyright  2026
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class text_converter {

    /** Regex fragment matching « (raw or as an HTML entity). */
    const LAQUO = '(?:«|&laquo;|&#0*171;|&#[xX]0*[aA][bB];)';
    /** Regex fragment matching » (raw or as an HTML entity). */
    const RAQUO = '(?:»|&raquo;|&#0*187;|&#[xX]0*[bB][bB];)';

    /** @var mathml_to_latex */
    protected $engine;

    /** @var bool also convert plain <math> MathML. */
    protected $convertplainmathml;

    /**
     * Constructor.
     *
     * @param bool $convertplainmathml whether plain <math> elements are also converted
     */
    public function __construct(bool $convertplainmathml = true) {
        $this->engine = new mathml_to_latex();
        $this->convertplainmathml = $convertplainmathml;
    }

    /**
     * Quick test: may the text contain a Wiris formula?
     *
     * @param string|null $text
     * @return bool
     */
    public static function might_contain_formula(?string $text): bool {
        if ($text === null || $text === '') {
            return false;
        }
        return stripos($text, 'math') !== false
            && (strpos($text, '«') !== false || stripos($text, '&laquo;') !== false
                || stripos($text, '&#171;') !== false || stripos($text, '&#xab;') !== false
                || stripos($text, '<math') !== false);
    }

    /**
     * Converts all the formulas of an HTML text.
     *
     * @param string $html
     * @return array ['text' => converted html, 'formulas' => list of formula reports]
     *     Each report: ['original' => string, 'latex' => ?string, 'ok' => bool, 'error' => ?string,
     *     'fromannotation' => bool, 'warnings' => string[]]
     */
    public function convert(string $html): array {
        $reports = [];

        // 1. Images generated by Wiris, carrying the formula in data-mathml.
        $html = preg_replace_callback('/<img\b[^>]*?\bdata-mathml\s*=\s*("[^"]*"|\'[^\']*\')[^>]*>/is',
            function($m) use (&$reports) {
                $value = substr($m[1], 1, -1);
                $value = html_entity_decode($value, ENT_QUOTES | ENT_HTML5, 'UTF-8');
                if (preg_match('/^\s*«/u', $value)) {
                    $mathml = $this->decode_safexml($value);
                } else {
                    $mathml = $value;
                }
                return $this->replace($m[0], $mathml, $reports);
            }, $html);

        // 2. SafeXML.
        $html = preg_replace_callback('/' . self::LAQUO . 'math\b.*?' . self::LAQUO . '\/math' . self::RAQUO . '/isu',
            function($m) use (&$reports) {
                return $this->replace($m[0], $this->decode_safexml($m[0]), $reports);
            }, $html);

        // 3. Plain MathML.
        if ($this->convertplainmathml) {
            $html = preg_replace_callback('/<(?:[a-zA-Z]+:)?math\b[^>]*>.*?<\/(?:[a-zA-Z]+:)?math>/is',
                function($m) use (&$reports) {
                    return $this->replace($m[0], $m[0], $reports);
                }, $html);
        }

        return ['text' => $html, 'formulas' => $reports];
    }

    /**
     * Decodes SafeXML into MathML, exactly as the Wiris filter does.
     *
     * @param string $safexml
     * @return string
     */
    public function decode_safexml(string $safexml): string {
        // The "Convert URLs into links" filter or the editor may have added tags (e.g. around the xmlns URL).
        $s = strip_tags($safexml);
        // The editor may have encoded characters as HTML entities (&laquo;, &nbsp;, &amp;...).
        $s = html_entity_decode($s, ENT_QUOTES | ENT_HTML5, 'UTF-8');
        $s = str_replace(['¨', '«', '»', '§', '`'], ['"', '<', '>', '&', "'"], $s);
        return $s;
    }

    /**
     * Converts one formula and returns the replacement text.
     *
     * @param string $original original text of the formula in the HTML
     * @param string $mathml decoded MathML
     * @param array $reports reports list (by reference)
     * @return string
     */
    protected function replace(string $original, string $mathml, array &$reports): string {
        $report = ['original' => $original, 'mathml' => $mathml, 'latex' => null, 'ok' => false, 'error' => null,
            'fromannotation' => false, 'warnings' => []];
        try {
            $mathml = trim($mathml);
            if (!preg_match('/^<(?:[a-zA-Z]+:)?math\b/', $mathml)) {
                throw new \InvalidArgumentException('No <math> element found');
            }
            $result = $this->engine->convert($mathml);
            $latex = $result['latex'];
            $report['warnings'] = $this->engine->warnings;
            $report['fromannotation'] = $result['fromannotation'];
            if (trim($latex) === '') {
                // Empty formula: remove it.
                $report['latex'] = '';
                $report['ok'] = true;
                $reports[] = $report;
                return '';
            }
            $report['latex'] = $latex;
            $report['ok'] = true;
            $reports[] = $report;
            return self::wrap($latex, $result['display']);
        } catch (\Throwable $e) {
            $report['error'] = $e->getMessage();
            $reports[] = $report;
            return $original;
        }
    }

    /**
     * Wraps LaTeX in MathJax delimiters, escaped for HTML.
     *
     * @param string $latex
     * @param bool $display
     * @return string
     */
    public static function wrap(string $latex, bool $display = false): string {
        $escaped = htmlspecialchars($latex, ENT_NOQUOTES, 'UTF-8');
        return $display ? '\\[' . $escaped . '\\]' : '\\(' . $escaped . '\\)';
    }
}
